// Writes src/generated-data.js from data/vendors.json and package.json.
//
// Why: importing JSON (`import x from './x.json' with { type: 'json' }`) prints an
// "ExperimentalWarning" on every run in Node 20.10-20.17 and 22.0-22.11. A plain JavaScript
// module loads silently on every Node version and in every bundler.
//
// data/vendors.json stays the file you edit. Run `npm run generate` afterwards;
// test/generated-data.test.js fails if you forget.
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';

const read = (path) => JSON.parse(fs.readFileSync(new URL(`../${path}`, import.meta.url), 'utf8'));

export function generatedSource() {
  const pkg = read('package.json');
  const vendors = read('data/vendors.json');
  return `// Generated by scripts/generate-data.js from data/vendors.json and package.json.
// Do not edit by hand: change those files and run \`npm run generate\`.

/** The published package version. */
export const VERSION = ${JSON.stringify(pkg.version)};

/** The vendor database (same content as data/vendors.json). */
export const vendorData = ${JSON.stringify(vendors)};
`;
}

// Run directly (npm run generate): write the file. Imported (by the test): only compare.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  fs.writeFileSync(new URL('../src/generated-data.js', import.meta.url), generatedSource());
  console.log('Wrote src/generated-data.js');
}
